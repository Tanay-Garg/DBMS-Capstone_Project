

CREATE TABLE IF NOT EXISTS app_migrations (
  migration_key TEXT PRIMARY KEY,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS customers (
  customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name TEXT NOT NULL CHECK (length(trim(full_name)) >= 2),
  email TEXT NOT NULL,
  phone TEXT NOT NULL,
  license_number TEXT NOT NULL UNIQUE,
  joined_on DATE NOT NULL DEFAULT CURRENT_DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_customers_email_lower ON customers (lower(email));

CREATE TABLE IF NOT EXISTS vehicles (
  vehicle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  make TEXT NOT NULL,
  model TEXT NOT NULL,
  year INTEGER NOT NULL CHECK (year BETWEEN 1990 AND 2100),
  license_plate TEXT NOT NULL,
  category TEXT NOT NULL CHECK (category IN ('Economy','Sedan','SUV','Luxury','Electric','Van')),
  daily_rate NUMERIC(10,2) NOT NULL CHECK (daily_rate > 0),
  mileage INTEGER NOT NULL DEFAULT 0 CHECK (mileage >= 0),
  status TEXT NOT NULL DEFAULT 'Available' CHECK (status IN ('Available','Rented','Maintenance')),
  image_color TEXT NOT NULL DEFAULT '#dce8ee',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_vehicles_plate_lower ON vehicles (lower(license_plate));

CREATE TABLE IF NOT EXISTS bookings (
  booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES customers(customer_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  vehicle_id BIGINT NOT NULL REFERENCES vehicles(vehicle_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  pickup_date DATE NOT NULL,
  return_date DATE NOT NULL,
  status TEXT NOT NULL DEFAULT 'Confirmed' CHECK (status IN ('Pending','Confirmed','Cancelled','Converted')),
  estimated_total NUMERIC(10,2) NOT NULL CHECK (estimated_total >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (return_date > pickup_date)
);

CREATE TABLE IF NOT EXISTS rentals (
  rental_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES customers(customer_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  vehicle_id BIGINT NOT NULL REFERENCES vehicles(vehicle_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  booking_id BIGINT UNIQUE REFERENCES bookings(booking_id) ON UPDATE CASCADE ON DELETE SET NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  actual_return_date DATE,
  status TEXT NOT NULL DEFAULT 'Active' CHECK (status IN ('Active','Completed','Overdue','Cancelled')),
  total_amount NUMERIC(10,2) NOT NULL CHECK (total_amount >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS payments (
  payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rental_id BIGINT NOT NULL REFERENCES rentals(rental_id) ON UPDATE CASCADE ON DELETE CASCADE,
  amount NUMERIC(10,2) NOT NULL CHECK (amount > 0),
  payment_date DATE NOT NULL DEFAULT CURRENT_DATE,
  method TEXT NOT NULL CHECK (method IN ('Card','Cash','Bank transfer','UPI')),
  status TEXT NOT NULL DEFAULT 'Paid' CHECK (status IN ('Paid','Pending','Refunded','Failed')),
  reference TEXT NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS maintenance (
  maintenance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehicle_id BIGINT NOT NULL REFERENCES vehicles(vehicle_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  service_type TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  service_date DATE NOT NULL,
  cost NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (cost >= 0),
  status TEXT NOT NULL DEFAULT 'Scheduled' CHECK (status IN ('Scheduled','In progress','Completed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_bookings_customer ON bookings(customer_id);
CREATE INDEX IF NOT EXISTS idx_bookings_vehicle_dates ON bookings(vehicle_id, pickup_date, return_date);
CREATE INDEX IF NOT EXISTS idx_rentals_customer_status ON rentals(customer_id, status);
CREATE INDEX IF NOT EXISTS idx_rentals_vehicle_status ON rentals(vehicle_id, status);
CREATE INDEX IF NOT EXISTS idx_payments_rental_date ON payments(rental_id, payment_date);
CREATE INDEX IF NOT EXISTS idx_maintenance_vehicle_date ON maintenance(vehicle_id, service_date);

CREATE OR REPLACE VIEW rental_details AS
SELECT r.rental_id, c.full_name AS customer, v.make || ' ' || v.model AS vehicle,
       v.license_plate, r.start_date, r.end_date, r.status, r.total_amount,
       COALESCE(SUM(CASE WHEN p.status='Paid' THEN p.amount ELSE 0 END),0) AS amount_paid
FROM rentals r
JOIN customers c ON c.customer_id=r.customer_id
JOIN vehicles v ON v.vehicle_id=r.vehicle_id
LEFT JOIN payments p ON p.rental_id=r.rental_id
GROUP BY r.rental_id, c.customer_id, v.vehicle_id;

CREATE OR REPLACE FUNCTION autoflow_rental_vehicle_status() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.status IN ('Active','Overdue') THEN
      UPDATE vehicles SET status='Rented' WHERE vehicle_id=NEW.vehicle_id AND status='Available';
      UPDATE bookings SET status='Converted' WHERE booking_id=NEW.booking_id;
    END IF;
    RETURN NEW;
  END IF;
  IF NEW.status IN ('Completed','Cancelled') THEN
    UPDATE vehicles SET status='Available' WHERE vehicle_id=NEW.vehicle_id AND status='Rented';
  ELSIF NEW.status IN ('Active','Overdue') AND OLD.status IN ('Completed','Cancelled') THEN
    UPDATE vehicles SET status='Rented' WHERE vehicle_id=NEW.vehicle_id AND status='Available';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS rental_vehicle_status ON rentals;
CREATE TRIGGER rental_vehicle_status
AFTER INSERT OR UPDATE OF status ON rentals
FOR EACH ROW EXECUTE FUNCTION autoflow_rental_vehicle_status();

CREATE OR REPLACE FUNCTION autoflow_maintenance_vehicle_status() RETURNS trigger AS $$
BEGIN
  IF NEW.status IN ('Scheduled','In progress') THEN
    UPDATE vehicles SET status='Maintenance' WHERE vehicle_id=NEW.vehicle_id AND status='Available';
  ELSIF NEW.status='Completed' THEN
    UPDATE vehicles SET status='Available' WHERE vehicle_id=NEW.vehicle_id AND status='Maintenance';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS maintenance_vehicle_status ON maintenance;
CREATE TRIGGER maintenance_vehicle_status
AFTER INSERT OR UPDATE OF status ON maintenance
FOR EACH ROW EXECUTE FUNCTION autoflow_maintenance_vehicle_status();
